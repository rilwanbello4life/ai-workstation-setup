#!/usr/bin/env bash
# Phase 8.5 - ComfyUI for image and video generation.
#
# Models are kept outside the ComfyUI checkout so that git updates never touch
# tens of gigabytes of weights.

source "$(dirname "${BASH_SOURCE[0]}")/common.sh"
require_not_root

APP="${APPS}/ComfyUI"
MODELS="$AI_ROOT/comfyui/models"
OUTPUT="$AI_ROOT/comfyui/output"

ensure_ai_dirs

section "Source"

mkdir -p "$APPS"
if [[ -d "$APP/.git" ]]; then
    info "Updating existing checkout."
    git -C "$APP" pull --ff-only
else
    git clone https://github.com/comfyanonymous/ComfyUI.git "$APP"
fi
ok "Source at $APP"

section "Virtual environment"

VENV="$APP/.venv"
if have uv; then
    [[ -d "$VENV" ]] || uv venv "$VENV" --python 3.12
    PY="$VENV/bin/python"
    PIP=(uv pip install --python "$PY")
else
    [[ -d "$VENV" ]] || python3 -m venv "$VENV"
    PY="$VENV/bin/python"
    PIP=("$PY" -m pip install)
fi
ok "venv at $VENV"

section "PyTorch"

info "Installing from the cu128 index (required for Blackwell sm_120)."
"${PIP[@]}" torch torchvision torchaudio --index-url https://download.pytorch.org/whl/cu128

section "ComfyUI requirements"

"${PIP[@]}" -r "$APP/requirements.txt"
ok "Dependencies installed."

section "Custom nodes"

NODES="$APP/custom_nodes"
mkdir -p "$NODES"

install_node() {
    local name="$1" url="$2"
    local target="$NODES/$name"
    if [[ -d "$target/.git" ]]; then
        info "$name already present."
        git -C "$target" pull --ff-only >/dev/null 2>&1 || true
    else
        git clone "$url" "$target"
        [[ -f "$target/requirements.txt" ]] && "${PIP[@]}" -r "$target/requirements.txt"
        ok "$name installed."
    fi
}

install_node ComfyUI-Manager https://github.com/ltdrdata/ComfyUI-Manager.git
# Needed for the quantised Wan 2.2 14B video weights.
install_node ComfyUI-GGUF    https://github.com/city96/ComfyUI-GGUF.git

section "Shared model paths"

for sub in checkpoints diffusion_models unet text_encoders vae loras clip_vision upscale_models; do
    mkdir -p "$MODELS/$sub"
done
mkdir -p "$OUTPUT"

cat > "$APP/extra_model_paths.yaml" <<EOF
# Generated by ai-workstation-setup.
# Keeps models outside the ComfyUI checkout so git updates never touch one copy
# of every checkpoint.
local:
    base_path: $MODELS
    checkpoints: checkpoints
    diffusion_models: diffusion_models
    unet: unet
    text_encoders: text_encoders
    clip: text_encoders
    vae: vae
    loras: loras
    clip_vision: clip_vision
    upscale_models: upscale_models
EOF
ok "Wrote $APP/extra_model_paths.yaml"

section "Launcher"

launcher="$APPS/start-comfyui.sh"
cat > "$launcher" <<EOF
#!/usr/bin/env bash
# Loopback only. ComfyUI has no authentication and can execute code through the
# editor, so never add --listen. Use an SSH tunnel for remote access.
set -euo pipefail
cd "$APP"
exec "$PY" main.py --output-directory "$OUTPUT" "\$@"
EOF
chmod +x "$launcher"
ok "Wrote $launcher"

section "Next"

cat <<EOF
  Start it:   $launcher
  Open:       http://127.0.0.1:8188

  Download models (from the kit's models/ folder):
      ./download-models.sh image
      ./download-models.sh video

  Suggested first run: Templates -> Image -> Z-Image-Turbo: Text to Image.

  Reminder: image generation and Strata both want the GPU. Stop one before
  starting the other - 16 GB does not stretch to both.

  Next: ./06-voice.sh
EOF
